-- Postgres schema for Supabase (or any Postgres 14+).
--
--   npm run db:schema          (runs this file against DATABASE_URL)
--
-- Idempotent: every statement is IF NOT EXISTS / OR REPLACE, so it is safe to
-- re-run after a deploy. It replaces the CREATE TABLE / PRAGMA table_info
-- migrations that server/database.js used to run against SQLite at boot.
--
-- Choices made to keep the API byte-for-byte the same as the SQLite server:
--
--  * Timestamps that SQLite filled with CURRENT_TIMESTAMP are TEXT in the same
--    'YYYY-MM-DD HH:MM:SS' (UTC) shape, via utc_now_text(). A timestamptz
--    column would serialise as '2026-07-24T19:33:51.000Z' and change every
--    created_at the API returns.
--  * ISO strings the app writes itself (starts_at, expires_at, ...) stay TEXT
--    and are compared as strings, exactly as before. Those columns and the
--    ones the API sorts by use COLLATE "C" (byte order, like SQLite's BINARY)
--    so a locale collation can't reorder them.
--  * Flags stay INTEGER 0/1 (verified, pinned): the API returns raw rows.
--  * Emails use citext, the Postgres equivalent of COLLATE NOCASE.
--  * community_posts.resource_id has no foreign key. SQLite never enforced the
--    old one (PRAGMA foreign_keys was off), and enforcing it now would turn
--    deleting a resource that a post mentions into a 500.
--  * ids are GENERATED BY DEFAULT AS IDENTITY so the one-time SQLite import
--    can insert the original ids.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE OR REPLACE FUNCTION utc_now_text() RETURNS text
  LANGUAGE sql STABLE
  AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE TABLE IF NOT EXISTS resources (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text COLLATE "C" NOT NULL,
  organization text,
  type text NOT NULL,
  description text,
  address text NOT NULL,
  city text,
  state text,
  zip_code text,
  latitude double precision,
  longitude double precision,
  phone text,
  website text,
  hours text,
  source text,
  created_at text COLLATE "C" DEFAULT utc_now_text(),
  updated_at text COLLATE "C" DEFAULT utc_now_text(),
  slug text,
  services text,
  eligibility text,
  verified integer DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_resources_slug ON resources(slug);

CREATE TABLE IF NOT EXISTS community_posts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  content text NOT NULL,
  author text,
  resource_id integer,
  created_at text COLLATE "C" DEFAULT utc_now_text(),
  organization text,
  expires_at text COLLATE "C",
  category text DEFAULT 'update',
  pinned integer DEFAULT 0
);

-- Events are cancelled, never deleted (see the status column).
CREATE TABLE IF NOT EXISTS events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text UNIQUE,
  title text NOT NULL,
  description text,
  organization text NOT NULL,
  category text NOT NULL DEFAULT 'support',
  location_name text,
  address text,
  city text,
  state text,
  zip_code text,
  latitude double precision,
  longitude double precision,
  starts_at text COLLATE "C" NOT NULL,
  ends_at text COLLATE "C",
  status text NOT NULL DEFAULT 'scheduled',
  cancellation_note text,
  contact_phone text,
  resource_slug text,
  posted_by text,
  created_at text COLLATE "C" DEFAULT utc_now_text(),
  updated_at text COLLATE "C" DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS idx_events_starts_at ON events(starts_at);

-- Weekly maintenance moves finished events here (server/maintenance.js).
CREATE TABLE IF NOT EXISTS events_archive (
  id integer, slug text, title text, description text, organization text,
  category text, location_name text, address text, city text, state text,
  zip_code text, latitude double precision, longitude double precision,
  starts_at text COLLATE "C", ends_at text COLLATE "C",
  status text, cancellation_note text, contact_phone text, resource_slug text,
  posted_by text, created_at text, updated_at text,
  archived_at text DEFAULT utc_now_text()
);

-- Replaces data/archive.json (server/communityExport.js). One row per archived
-- item; `item` is the exact object that used to be appended to the file's
-- "events" or "posts" array, archivedAt included. json, not jsonb, so key
-- order survives.
CREATE TABLE IF NOT EXISTS community_archive (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('events', 'posts')),
  item json NOT NULL,
  archived_at text COLLATE "C" NOT NULL
);

-- --- Verified poster auth (design/VERIFIED-POSTER-AUTH.md) -------------------

CREATE TABLE IF NOT EXISTS allowlist (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email citext NOT NULL UNIQUE,
  org_name text COLLATE "C" NOT NULL,
  added_by text,
  added_at text DEFAULT utc_now_text()
);

-- What a signed-in address may do. Each role includes the ones before it:
--   publisher  events and posts (every allowlisted org)
--   editor     + the resource catalogue
--   admin      + the allowlist itself
ALTER TABLE allowlist ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'publisher';
DO $$
BEGIN
  ALTER TABLE allowlist ADD CONSTRAINT allowlist_role_check CHECK (role IN ('publisher', 'editor', 'admin'));
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;

-- Who changed which resource, and from what. Snapshots of the whole row, so a
-- bad edit can be read back and undone by hand.
CREATE TABLE IF NOT EXISTS resource_changes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id integer NOT NULL,
  action text NOT NULL,
  changed_by citext NOT NULL,
  changed_at text COLLATE "C" DEFAULT utc_now_text(),
  before jsonb,
  after jsonb
);
CREATE INDEX IF NOT EXISTS idx_resource_changes_resource ON resource_changes(resource_id, id);

CREATE TABLE IF NOT EXISTS auth_codes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email citext NOT NULL,
  code_hash text NOT NULL,
  expires_at text COLLATE "C" NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  created_at text DEFAULT utc_now_text()
);
CREATE INDEX IF NOT EXISTS idx_auth_codes_email ON auth_codes(email);

CREATE TABLE IF NOT EXISTS sessions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash text NOT NULL UNIQUE,
  email citext NOT NULL,
  org_name text NOT NULL,
  expires_at text COLLATE "C" NOT NULL,
  created_at text DEFAULT utc_now_text(),
  last_used_at text
);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS organizations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text COLLATE "C" NOT NULL UNIQUE,
  website text,
  social_media text,
  description text,
  created_at text DEFAULT utc_now_text()
);

-- --- Login rate limiting -----------------------------------------------------
-- Replaces the in-memory Map in authController.js, which only held within one
-- process. Serverless instances share nothing, so the counters live here.
-- One row per counted request; rate_limit_hit() is the only writer.

CREATE TABLE IF NOT EXISTS rate_limit_hits (
  key text NOT NULL,
  hit_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS idx_rate_limit_hits_key ON rate_limit_hits(key, hit_at);

-- Sliding window, same rule as the old Map: if `key` already has `max` hits in
-- the last `window_ms`, return true (limited) and record nothing; otherwise
-- record a hit and return false. The advisory lock serialises concurrent calls
-- for one key, so two instances can't both slip under the limit.
CREATE OR REPLACE FUNCTION rate_limit_hit(p_key text, p_max integer, p_window_ms integer)
RETURNS boolean
LANGUAGE plpgsql
AS $$
DECLARE
  recent integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('rate_limit:' || p_key));
  DELETE FROM rate_limit_hits
    WHERE key = p_key AND hit_at <= clock_timestamp() - make_interval(secs => p_window_ms / 1000.0);
  SELECT count(*) INTO recent FROM rate_limit_hits WHERE key = p_key;
  IF recent >= p_max THEN
    RETURN true;
  END IF;
  INSERT INTO rate_limit_hits (key) VALUES (p_key);
  RETURN false;
END
$$;

-- --- Lock out Supabase's public Data API ------------------------------------
-- The server connects as the table owner, which bypasses RLS. Supabase also
-- exposes the public schema over PostgREST to the anon/authenticated roles;
-- RLS with no policies, plus revoking their grants, keeps session hashes and
-- the allowlist unreachable that way. No-ops on a plain local Postgres.

ALTER TABLE resources ENABLE ROW LEVEL SECURITY;
ALTER TABLE community_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
ALTER TABLE events_archive ENABLE ROW LEVEL SECURITY;
ALTER TABLE community_archive ENABLE ROW LEVEL SECURITY;
ALTER TABLE allowlist ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE organizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limit_hits ENABLE ROW LEVEL SECURITY;
ALTER TABLE resource_changes ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON FUNCTION rate_limit_hit(text, integer, integer) FROM PUBLIC;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
    REVOKE ALL ON FUNCTION rate_limit_hit(text, integer, integer) FROM anon, authenticated;
  END IF;
END
$$;
